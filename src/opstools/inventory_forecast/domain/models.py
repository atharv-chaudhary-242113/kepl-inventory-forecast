"""Canonical domain models for the inventory forecasting system.

These models define the business contracts exchanged between
application layers. They are intentionally independent of
Polars, StatsForecast, Excel workbooks, dashboards, and
external infrastructure.

Engine modules perform calculations.

Domain models describe business reality.
"""

