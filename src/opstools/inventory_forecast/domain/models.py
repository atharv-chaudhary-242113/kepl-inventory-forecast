@dataclass(frozen=True, slots=True)
class ReplenishmentRecommendation:
    """Recommend quantity required to restore an item to its target inventory level.

    POV can safely be assumed as the data for previous day's demand
    as orders are only placed after items are used or sold.
    Closing Stock shows the baseline or target stock level.

    Attributes:
        item_id:
            Inventory item identifier.

        baseline_stock_level:
            Target stock level (closing-stock).

        estimate_stock_level:
            Current estimated stock level of the company.

        replenishment_quantity:
            Suggested replenishment quantity (the difference).
    """

    item_id: str

    baseline_stock_level: float
    estimate_stock_level: float

    replenishment_quantity: float

    def __post_init__(self) -> None:
        """Validate replenishment recommendation."""
        if self.baseline_stock_level < 0:
            raise ValueError("baseline stock level cannot be negative.")

        if self.estimate_stock_level < 0:
            raise ValueError("estimated stock level cannot be negative.")

        if self.replenishment_quantity < 0:
            raise ValueError("replenishment quantity cannot be negative.")


