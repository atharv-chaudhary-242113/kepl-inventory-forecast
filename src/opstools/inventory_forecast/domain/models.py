@dataclass(frozen=True, slots=True)
class ForecastRequest:
    """Input contract for forecast generation.

    Encapsulates all configuration required to produce a
    demand forecast for a single inventory item.

    This model serves as the public entry point into the
    forecasting subsystem.

    Attributes:
        item_id:
            Unique inventory item identifier.

        horizon:
            Number of future periods to forecast.

        seasonality:
            Seasonal cycle length used by seasonal models.

        service_level:
            Target service level expressed as a decimal
            probability between 0 and 1.
    """

    item_id: str

    horizon: int

    seasonality: int

    service_level: float

    def __post_init__(self) -> None:
        """Validate forecast request."""
        if self.horizon <= 0:
            raise ValueError("horizon must be positive.")

        if self.seasonality <= 0:
            raise ValueError("seasonality must be positive.")

        if not 0.0 <= self.service_level <= 1.0:
            raise ValueError("service_level must be between 0 and 1.0.")


@dataclass(frozen=True, slots=True)
class ForecastMetrics:
    """Forecast performance metrics produced during model evaluation and backtesting.

    These metrics are used to compare competing forecast
    models and select the best-performing model for a
    specific inventory item.

    Attributes:
        mase:
            Mean Absolute Scaled Error.

        rmsse:
            Root Mean Squared Scaled Error.

        bias:
            Average forecast bias. Positive values indicate
            overforecasting while negative values indicate
            underforecasting.

        mae:
            Mean Absolute Error.

        rmse:
            Root Mean Squared Error.

        observation_count:
            Number of observations used during evaluation.
    """

    mase: float

    rmsse: float

    bias: float

    mae: float

    rmse: float

    observation_count: int

    def __post_init__(self) -> None:
        """Validate metric values."""
        if self.mase < 0:
            raise ValueError("MASE cannot be negative.")

        if self.rmsse < 0:
            raise ValueError("RMSSE cannot be negative.")

        if self.mae < 0:
            raise ValueError("MAE cannot be negative.")

        if self.rmse < 0:
            raise ValueError("RMSE cannot be negative.")

        if self.observation_count <= 0:
            raise ValueError("Observation count must be positive.")


@dataclass(frozen=True, slots=True)
class ForecastResult:
    """Final demand forecast produced for an inventory item.

    Represents the selected forecasting model, forecasted
    demand values, prediction intervals, and model
    evaluation metrics.

    This is the primary output of the forecasting subsystem
    and serves as an input to replenishment planning and
    inventory analytics.

    Attributes:
        item_id:
            Unique inventory item identifier.

        demand_class:
            SBC demand classification assigned during
            demand analysis.

        selected_model:
            Forecasting model selected after evaluation.

        forecast_values:
            Forecasted demand quantities for future periods.

        lower_bound:
            Lower prediction interval values corresponding
            to each forecast period.

        upper_bound:
            Upper prediction interval values corresponding
            to each forecast period.

        metrics:
            Forecast evaluation metrics generated during
            backtesting.

        status:
            Forecast status after evaluation.

        generated_at:
            UTC timestamp indicating when the forecast
            was produced.
    """

    item_id: str

    demand_class: SbcClass

    selected_model: ForecastModel

    forecast_values: tuple[float, ...]

    lower_bound: tuple[float, ...]

    upper_bound: tuple[float, ...]

    metrics: ForecastMetrics

    status: ForecastStatus

    generated_at: datetime

    def __post_init__(self) -> None:
        """Validate forecast result."""
        expected = len(self.forecast_values)

        if expected == 0:
            raise ValueError("forecast_values cannot be empty.")

        if len(self.lower_bound) != expected:
            raise ValueError("lower_bound length must match forecast_values length.")

        if len(self.upper_bound) != expected:
            raise ValueError("upper_bound length must match forecast_values length.")


